    def calculate_bayesian_posterior(self, prior: float, likelihood_ratio: float) -> float:
        """
        Calculates posterior probability given prior and likelihood ratio.
        P(H|D) = (Prior * LR) / [Prior * LR + (1 - Prior)]
        When LR = 1.0, Posterior = Prior.
        """
        if prior <= 0.0:
            return 0.0
        if prior >= 1.0:
            return 1.0
        if likelihood_ratio == math.inf:
            return 1.0
        if likelihood_ratio == 0.0:
            return 0.0
        numerator = prior * likelihood_ratio
        denominator = numerator + (1.0 - prior)
        return numerator / denominator

